def find(prefix: str, quote: str | None = None) -> dict:
    hits = [i for aid, i in index().items() if aid.startswith(prefix)]
    if quote is not None:
        hits = [i for i in hits if quote in i['text']]
    scoped = [i for i in hits if i['author'] == prefix.split('-')[0]]
    if scoped:
        hits = scoped
    blocks = [i for i in hits if not i['layer'].startswith('整条')]
    if blocks:
        hits = blocks
    if len(hits) != 1:
        raise ValueError(f'出处须唯一：{prefix}，实际{len(hits)}条')
    return get_source(hits[0]['anchor_id'])


def ref(prefix: str, quote: str) -> dict:
    source = find(prefix, quote)
    return {'anchor_id': source['anchor_id'], 'quote': quote,
            'path': source['path'], 'note_sha256': source['note_sha256'],
            'author': source['author'], 'pending': source['pending'],
            'polluted': source['polluted'], 'layer': source['layer']}


